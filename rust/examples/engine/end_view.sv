// The end view: what the assembly adds to the section through cylinder 1 beyond its parts — the
// bore axis the crank and rods are placed against, and the timing drive on the front of the
// engine.  The block, the head, the crankshaft, the rods and the piston are parts of their own
// (`engine.block`, `engine.head`, `engine.crankshaft`, `engine.conrod`), drawn in this view by
// the document.

use engine.dims (deck, front, rcamj, rcp)
use engine.parts
use std (coords, slides, turns)
use std

// -- the timing belt --------------------------------------------------------------------------
// A toothed belt of trapezoidal teeth, flanks 20° from square to the belt (40° included, the
// classic timing-belt form), on a pitch that puts `nt` of them round the crank pulley's pitch
// circle: the table's `rcp`, so the cam pulleys, twice as many teeth on the same pitch, come out
// at its `rcam`.  The belt's pitch line runs through its cords, `pld` outside the land between
// teeth, so a pulley's tips stand `pld` inside its pitch circle where the land rests on them.
// Every size of the tooth is a fraction of the pitch, so it follows the table.
nt := 20                       // crank pulley teeth; each cam pulley has `2 nt`
tpitch := 2 * pi * rcp / nt    // the belt's pitch, along its pitch line
bw := 0.49 * tpitch            // a tooth's width at its root, on the land
bh := 0.2 * tpitch             // a tooth's height, land to tip
pld := 0.04 * tpitch           // the pitch line, past the land: the cords' line
bt := 0.18 * tpitch            // the belt's back, past the land
alpha := 20deg                 // a flank's angle from square to the belt

// Along the crank axis, every pulley spans the same stretch forward of the block's front face,
// the belt its teeth less a millimetre either side; a flanged pulley keeps a guide flange at
// each end, standing `bt + 2mm` past the belt's back, and the teeth between them.
xp0 := front - 55mm
xp1 := front - 30mm
wf := 2mm                      // a flange's thickness
rnose := 16mm                  // the crank's nose, which the crank pulley is bored to
ridl := 16mm                   // the tensioner's roller, and where it stands off the crank:
idl_dx := 54mm                 // outside the slack run, pressing it in some 6 mm
idl_dy := 150mm

// A timing pulley of `n` teeth on the crank axis at `o`, generated by the belt's own tooth: the
// tooth, drawn in the belt as it stands on the pulley's pitch circle at its pitch point, slides
// along the pitch line as the blank turns, so the line rolls on the pitch circle without
// slipping — which is how a belt rides a pulley — and what the tooth sweeps through, seen from
// the blank, is one tooth space.  Its flanks are involutes of the circle `rp cos(alpha)`, its root
// the trochoids of the tooth's tip corners: nothing here states either.  Indexed a pitch apart
// round the blank, the spaces cut the teeth (`rack_cut_gear.sv` cuts a spur gear so).
//
// `up` says which side of the centre the generating tooth is drawn on — 1 above, -1 below — so
// it stands where the belt wraps the pulley.  It is drawn in `radial`, the axes through
// the centre whose u runs out to the pitch point, which is also where the class is read in (the
// exact build of a rack's sweep is refused for a profile drawn in `std.side`'s own axes, whose
// u runs along the world's y: a concave corner where the tooth's tip is convex).  `flanged` is
// 1 for a pulley with guide flanges, 0 for one whose teeth run its whole width.
part Pulley(o: point, n: Int, bore: Length, up: Scalar, flanged: Int) {
  rp := n * tpitch / (2 * pi)
  in o.plane {
    tip := circle(center: o) hint(r: rp - pld)
    pitch := circle(center: o) hint(r: rp)
    root := circle(center: o) hint(r: rp - pld - bh)
    hole := circle(center: o) hint(r: bore)
    radius(rp - pld) tip
    radius(rp) pitch
    radius(rp - pld - bh) root
    radius(bore) hole
    // the pitch point, and the pitch line through it the belt slides along
    s0 := point hint((o.x, o.y + up * rp))
    s1 := point hint((o.x - up * 10mm, o.y + up * rp))
    o distance(up * rp, along: v) s0
    o level(u) s0
    s0 distance(-up * 10mm, along: u) s1
    s0 level(v) s1
    construction line_of_pitch := line(s0, s1)
  }
  radial := std.Turned(o, s0) in o.plane
  in (belt := frame) {
    in radial.axes {
      t0 := point hint((rp - pld - bh, -(bw / 2 - bh * tan(alpha))))
      t1 := point hint((rp - pld - bh, bw / 2 - bh * tan(alpha)))
      t2 := point hint((rp + 1mm, bw / 2 + (pld + 1mm) * tan(alpha)))
      t3 := point hint((rp + 1mm, -(bw / 2 + (pld + 1mm) * tan(alpha))))
      t0 coords(du: rp - pld - bh, dv: -(bw / 2 - bh * tan(alpha))) radial.axes
      t1 coords(du: rp - pld - bh, dv: bw / 2 - bh * tan(alpha)) radial.axes
      t2 coords(du: rp + 1mm, dv: bw / 2 + (pld + 1mm) * tan(alpha)) radial.axes
      t3 coords(du: rp + 1mm, dv: -(bw / 2 + (pld + 1mm) * tan(alpha))) radial.axes
    }
  }
  // the tooth, from its tip to past the pulley's tips (a point of it outside them never reaches
  // the blank), and through the pulley either way
  tooth := face(t0, t1, t2, t3, -> close)
  construction belt_tooth := solid(tooth, from: xp0 - 2mm, to: xp1 + 2mm)

  // The blank turns about its spindle, the line out of the view through its centre, and the belt
  // runs along the pitch line a pitch circle a turn, the way the pitch point turns.  Each axis
  // runs the way it is drawn: the spindle out along the view's normal, the belt from `s0` to
  // `s1`, and `radial`'s u and v out to the pitch point and along the pitch line (bounds, so
  // which root is meant is stated, not left to the seeds).
  out := point hint((10mm, o.x, o.y))
  construction spindle := line(o, out)
  out distance(10mm, along: n) o.plane
  spindle parallel o.plane.normal
  turn := frame
  turn turns(1) spindle
  belt slides(2 * pi * rp) line_of_pitch
  o distance(>= 1mm, along: turn.axis) out
  s0 distance(>= 1mm, along: belt.axis) s1
  o distance(>= 1mm, along: radial.axes.u) s0
  s0 distance(>= 1mm, along: radial.axes.v) s1
  construction space := sweep(belt_tooth, through: pulley, seen_from: turn)

  construction blank := solid(face(tip), from: xp0 + flanged * wf, to: xp1 - flanged * wf)
  construction bored := solid(face(hole), from: xp0 - 2mm, to: xp1 + 2mm)
  pulley := solid(blank)
  bored cut pulley
  repeat n as i {
    construction indexed := space at(under: turn) i * 360deg / n
    indexed cut pulley
  }

  // the guide flanges either side of the teeth, a solid of their own: cut from the toothed
  // pulley, they would be a Boolean of its generated sheets, which costs more than the teeth
  when flanged == 1 {
    in o.plane {
      rim := circle(center: o) hint(r: rp - pld + bt + 2mm)
      radius(rp - pld + bt + 2mm) rim
    }
    construction near := solid(face(rim), from: xp0, to: xp0 + wf)
    construction far := solid(face(rim), from: xp1 - wf, to: xp1)
    flanges := solid(near)
    far union flanges
    bored cut flanges
  }
}

// The timing drive on the front of the engine: the crank pulley, flanged, under the crank; a cam
// pulley of twice its teeth on each camshaft, so the cams turn at half its speed; and the belt
// round them, its slack side — the run up from the crank to the intake cam — pressed in by a
// tensioner's roller on its back.  The belt is drawn as it is made: its inside, the land
// between its teeth, lies on each pulley's tips round its wrap and runs straight between them,
// and its back stands `bt` outside that, so on the roller it is the back that bears and the
// inside that stands off.  Each loop is one chain round the drive, every joint tangent: the
// runs leave one wrap and meet the next without a crease, and where each wrap starts and ends is
// where its runs touch it.  The belt is the band between them, across its width.
part Drive(o: point, cam_i: point, cam_e: point) {
  crank := Pulley(o, n: nt, bore: rnose, up: -1, flanged: 1)
  intake := Pulley(cam_i, n: 2 * nt, bore: rcamj, up: 1, flanged: 0)
  exhaust := Pulley(cam_e, n: 2 * nt, bore: rcamj, up: 1, flanged: 0)
  ri := rcp - pld                // the crank pulley's tips
  rk := 2 * rcp - pld            // a cam pulley's: twice the crank's teeth on its pitch
  // the tensioner's roller, outside the slack run, pressing it in
  idl := engine.parts.At(o, dx: idl_dx, dy: idl_dy) in o.plane
  in o.plane {
    roller := circle(center: idl.p) hint(r: ridl)
    radius(ridl) roller
    pin := circle(center: idl.p) hint(r: 6mm)
    radius(6mm) pin
    // the inside, round the drive counter-clockwise: off the roller (the other way round it,
    // the belt's back on it) up to the intake cam, over to the exhaust cam, down to the crank,
    // round under it and up the slack run back onto the roller.  The roller's wrap is an arc
    // counter-clockwise from where the belt leaves it to where the belt arrives, so the belt
    // walks it backwards, and its two tangencies are stated at its ends.
    ia := point hint((idl.p.x - ridl - bt, idl.p.y - 5mm))
    ib := point hint((idl.p.x - ridl - bt, idl.p.y + 5mm))
    wi := arc(center: idl.p, start: ib, end: ia) hint(r: ridl + bt)
    radius(ridl + bt) wi
    (sk := line(ib, hint((cam_i.x + rk, cam_i.y - 3mm)))) ->
      tangent radius(rk) (wk := arc(center: cam_i) hint(r: rk)) ->
      tangent (st := line(hint((cam_i.x, cam_i.y + rk)), hint((cam_e.x, cam_e.y + rk)))) ->
      tangent radius(rk) (we := arc(center: cam_e) hint(r: rk)) ->
      tangent (se := line(hint((cam_e.x - rk, cam_e.y - 3mm)), hint((o.x - ri, o.y + 3mm)))) ->
      tangent radius(ri) (wc := arc(center: o) hint(r: ri)) ->
      tangent (si := line(hint((o.x + ri, o.y + 3mm)), ia))
    wi tangent(at: start) sk
    wi tangent(at: end) si
    // the back, `bt` outside it all the way round
    ba := point hint((idl.p.x - ridl, idl.p.y - 5mm))
    bb := point hint((idl.p.x - ridl, idl.p.y + 5mm))
    vi := arc(center: idl.p, start: bb, end: ba) hint(r: ridl)
    radius(ridl) vi
    (bk := line(bb, hint((cam_i.x + rk + bt, cam_i.y - 3mm)))) ->
      tangent radius(rk + bt) (vk := arc(center: cam_i) hint(r: rk + bt)) ->
      tangent (bm := line(hint((cam_i.x, cam_i.y + rk + bt)),
                          hint((cam_e.x, cam_e.y + rk + bt)))) ->
      tangent radius(rk + bt) (ve := arc(center: cam_e) hint(r: rk + bt)) ->
      tangent (be := line(hint((cam_e.x - rk - bt, cam_e.y - 3mm)),
                          hint((o.x - ri - bt, o.y + 3mm)))) ->
      tangent radius(ri + bt) (vc := arc(center: o) hint(r: ri + bt)) ->
      tangent (bi := line(hint((o.x + ri + bt, o.y + 3mm)), ba))
    vi tangent(at: start) bk
    vi tangent(at: end) bi
  }
  construction inside := face(si, wi, sk, wk, st, we, se, wc)
  belt := solid(face(bi, vi, bk, vk, bm, ve, be, vc, holes: inside), from: xp0 + wf + 1mm,
                to: xp1 - wf - 1mm)

  tensioner := solid(face(roller, holes: pin), from: xp0 + wf, to: xp1 - wf)
}

part EndSection(o: point) {
  top := engine.parts.At(o, dx: 0mm, dy: deck + 30mm)
  bore := line(o, top.p)
}

// Open this file to preview what the end view adds: the bore axis, and the timing drive on the
// crank and on the two camshafts where the head carries them, its pulleys, belt and tensioner as
// solids.
preview {
  unit mm
  in std.side {
    end := EndSection(std.side.origin)
    cam_i := engine.parts.At(std.side.origin, dx: engine.dims.camx,
                             dy: engine.dims.camh + engine.dims.gasket)
    cam_e := engine.parts.At(std.side.origin, dx: -engine.dims.camx,
                             dy: engine.dims.camh + engine.dims.gasket)
  }
  // the drive draws itself in the plane its centres are drawn in
  drive := Drive(std.side.origin, cam_i.p, cam_e.p)
}
