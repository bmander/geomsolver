// The crankshaft, designed in one place.
//
// One component, two views (§6.7): looking along the axis it is a section through cylinder 1's
// throw — the main journal, the crank pin in its eye, the web flaring out from the eye to a
// counterweight whose rim is an arc about the axis, and the oil passage drilled from journal to
// pin — with the throw of cylinders 2 and 3 ghosted in a half turn on.  Looking across it is the
// whole shaft edge on: the nose the pulley sits on, five main journals, four pins on the cylinder
// pitch with their webs between, the flange the flywheel bolts to, and the flywheel with the
// starter's ring gear shrunk on its rim.  The webs' heights in the side view are the crowns and
// heels of the end view's throws, by projection, inside the part.
//
// An inline four's pins lie in one plane, cylinders 1 and 4 up together and 2 and 3 a half turn
// on, which is why one section and its ghost place all four pins.
//
// As a solid the shaft is the section's pieces swept along the axis over the stretches the side
// view gives them, and then machined: an oil drilling slanting through each web from a main
// journal to its pin, a keyway and a tapped bore in the nose for the pulley, the pilot bearing's
// bore in the flange, and the flywheel bolted to it, dished on its engine side and stepped at its
// clutch face.  The starter's ring gear is a solid of its own, its teeth generated by a rack.

use engine.dims (P, R, back, front, pinlen, rflange, rfw, rj, rp, rseal, wflange, wfw)
use engine.parts
use std (horizontal, offset, slides, spins)

// -- the starter's ring gear --------------------------------------------------------------
// Its tip is the flywheel's outside, the table's `rfw`, and its count the starter's gearing (a
// real one has 100 to 130 teeth); the module is what the two leave, here 2.5.
zr := 110                       // teeth
mr := 2 * rfw / (zr + 2)        // module: the tip a module outside the pitch circle
alpha := 20deg                  // pressure angle
wring := 14mm                   // face width
rring := mr * zr / 2            // pitch radius
hf := 1.25 * mr                 // dedendum: the working depth and a quarter module's clearance
rseat := rfw - 16mm             // the ring's bore, and the flywheel's rim it is shrunk on

// One throw seen along the axis: the pin at `theta` from the bore axis, clockwise from top dead
// centre, in its eye; the web's two flanks leaving the eye tangent and running out to the
// counterweight rim; the rim an arc about the axis, `hcw` either side of the crank arm.  `crown`
// and `heel` are where the arm's line crosses the eye and the rim — the throw's extreme points,
// which the side view reads.
part Throw(o: point, ax: line, theta: Angle, shape: group) {
  pin := point hint((o.x + R * sin(theta), o.y + R * cos(theta)))
  arm := line(o, pin)
  o distance(R) pin
  ax angle(theta, sense: cw) arm
  kp := circle(center: pin) hint(r: rp)
  radius(rp) kp
  // the eye: the arc of the far side, between the two flank tangents
  el := point hint((pin.x - shape.eye * cos(theta), pin.y + shape.eye * sin(theta)))
  er := point hint((pin.x + shape.eye * cos(theta), pin.y - shape.eye * sin(theta)))
  eye := arc(center: pin, start: er, end: el) hint(r: shape.eye)
  radius(shape.eye) eye
  // the rim: an arc about the axis on the far side from the pin, `shape.half_width` either side of the arm
  cl := point hint((o.x - shape.rim * sin(theta + asin(shape.half_width / shape.rim)), o.y - shape.rim * cos(theta + asin(shape.half_width / shape.rim))))
  cr := point hint((o.x - shape.rim * sin(theta - asin(shape.half_width / shape.rim)), o.y - shape.rim * cos(theta - asin(shape.half_width / shape.rim))))
  rim := arc(center: o, start: cl, end: cr) hint(r: shape.rim)
  radius(shape.rim) rim
  cl distance(shape.half_width, side: left) arm
  cr distance(shape.half_width, side: right) arm
  // the flanks, tangent to the eye where they leave it
  fl := line(el, cl)
  fr := line(er, cr)
  fl tangent(at: p1) eye
  fr tangent(at: p1) eye
  // the crown of the eye and the heel of the rim, on the arm's own line
  crown := point hint((pin.x + shape.eye * sin(theta), pin.y + shape.eye * cos(theta)))
  heel := point hint((o.x - shape.rim * sin(theta), o.y - shape.rim * cos(theta)))
  crown coincident eye
  crown coincident arm
  heel coincident rim
  heel coincident arm
  // the oil passage, drilled slantwise through the web from the main journal's far side to the
  // pin's (the shaft draws the drilling): seen along the axis, along the arm across both
  oa := point hint((o.x - rj * sin(theta) - shape.oil_radius * cos(theta), o.y - rj * cos(theta) + shape.oil_radius * sin(theta)))
  ob := point hint((pin.x + rp * sin(theta) - shape.oil_radius * cos(theta), pin.y + rp * cos(theta) + shape.oil_radius * sin(theta)))
  oc := point hint((o.x - rj * sin(theta) + shape.oil_radius * cos(theta), o.y - rj * cos(theta) - shape.oil_radius * sin(theta)))
  od := point hint((pin.x + rp * sin(theta) + shape.oil_radius * cos(theta), pin.y + rp * cos(theta) - shape.oil_radius * sin(theta)))
  oil_l := line(oa, ob)
  oil_r := line(oc, od)
  oa distance(shape.oil_radius, side: left) arm
  ob distance(shape.oil_radius, side: left) arm
  oc distance(shape.oil_radius, side: right) arm
  od distance(shape.oil_radius, side: right) arm
  ob coincident kp
  od coincident kp
  oa distance(rj) o
  oc distance(rj) o
  // which root each point takes, the arm running from `o` up to the pin: each read against
  // points already placed, or against a rim corner, whose side of the arm is stated and whose
  // height up it turns none of these the other way.  The throw only turns about `o`, so no
  // triangle here comes near a line.  The passage's journal end on the far side of the axis
  // from the pin, its pin end on the far side of the pin from the axis
  ccw(o, cl, oa)
  cw(o, cr, oc)
  cw(pin, cl, ob)
  ccw(pin, cr, od)
  // the heel behind the axis, the crown beyond the pin
  ccw(o, cl, heel)
  cw(pin, cl, crown)
  // the rim's corners both behind the axis: neither in front, and not one each side, where the
  // two would stand in line with the axis
  ccw(cr, o, cl)
  // the eye inside each flank: the tangent from the rim's corner that wraps it
  ccw(el, cl, pin)
  cw(er, cr, pin)
}

// A web seen edge on: a rectangle between `x0` and `x1` along the axis whose top and bottom are
// the heights of two points the end view placed.
part WebSide(o: point, x0: Length, x1: Length, top: point, bottom: point) {
  a := point hint((o.x + x0, top.y))
  b := point hint((o.x + x1, top.y))
  c := point hint((o.x + x1, bottom.y))
  d := point hint((o.x + x0, bottom.y))
  (ab := line(a, b)) -> (bc := line(b, c)) -> (cd := line(c, d)) -> (da := line(d, a)) -> close
  o distance(x0, along: u) a
  top horizontal a
  o distance(x1, along: u) b
  top horizontal b
  o distance(x1, along: u) c
  bottom horizontal c
  o distance(x0, along: u) d
  bottom horizontal d
}

// The starter's ring gear, shrunk on the flywheel's rim: a ring `wring` wide from `at` along the
// axis, its teeth cut as a gear shaper's rack cutter cuts them (`generation/rack_cut_gear.sv`).
// The rack's tooth is a trapezoid, its flanks `alpha` from the radius and its tip a dedendum
// inside the pitch circle; it slides along its pitch line, tangent to the pitch circle on throw
// 1's arm, while the ring turns about the axis, so the line rolls on the pitch circle.  What the
// tooth sweeps through over the roll, seen from the ring, is one tooth space — involute flanks of
// the base circle, trochoid fillets at the root — and a copy of it each pitch round is cut from
// the ring, so the teeth stand where the crank's turn puts them.  `solventc --step` builds it
// exactly, one sector patterned into the whole.
//
// Seen along the axis it is drawn as a draughtsman draws a gear, by its tip, pitch and root
// circles, and its bore; edge on, as a band the face width wide with its root lines across it.
part StarterRing(o: point, arm: line, o_s: point, at: Length) {
  hw := pi * mr / 4             // half the rack tooth's thickness at the pitch line
  ht := hw - hf * tan(alpha)    // … and at its tip
  hb := hw + 2 * mr * tan(alpha)  // … and at its back, two modules out
  in o.plane {
    tip := circle(center: o) hint(r: rfw)
    radius(rfw) tip
    pitch := circle(center: o) hint(r: rring)
    radius(rring) pitch
    root := circle(center: o) hint(r: rring - hf)
    radius(rring - hf) root
    bore := circle(center: o) hint(r: rseat)
    radius(rseat) bore
    // the rack's pitch line, tangent to the pitch circle where throw 1's arm crosses it, and
    // running the way the ring's rim turns there, its two ends either side of the arm (one end
    // on the arm, square across the very middle of the space the rack cuts, the exact build has
    // refused, a loop of the cut left open)
    construction pp := point hint(at: o, toward: arm.p2, by: rring / R)
    construction s0 := point hint(at: o, toward: arm.p2, by: hypot(rring, 10mm) / R,
                                  turn: -atan(10mm / rring))
    construction s1 := point hint(at: o, toward: arm.p2, by: hypot(rring, 10mm) / R,
                                  turn: atan(10mm / rring))
    pp coincident(t == rring / R) arm
    s0 distance(10mm, side: right) arm
    s1 distance(10mm, side: left) arm
    pp level(arm) s0
    pp level(arm) s1
    construction slide := line(s0, s1)
  }
  // the rack's tooth, drawn in the rack where it stands at roll 0: its tip a dedendum in from the
  // pitch line, its back past the ring's tip
  in (rack := frame) {
    in o.plane {
      construction t0 := point hint(at: o, toward: arm.p2, by: hypot(rring - hf, ht) / R,
                                    turn: -atan(ht / (rring - hf)))
      construction t1 := point hint(at: o, toward: arm.p2, by: hypot(rring - hf, ht) / R,
                                    turn: atan(ht / (rring - hf)))
      construction t2 := point hint(at: o, toward: arm.p2, by: hypot(rring + 2 * mr, hb) / R,
                                    turn: atan(hb / (rring + 2 * mr)))
      construction t3 := point hint(at: o, toward: arm.p2, by: hypot(rring + 2 * mr, hb) / R,
                                    turn: -atan(hb / (rring + 2 * mr)))
      o distance(rring - hf, along: arm) t0
      o distance(rring - hf, along: arm) t1
      o distance(rring + 2 * mr, along: arm) t2
      o distance(rring + 2 * mr, along: arm) t3
      t0 distance(ht, side: right) arm
      t1 distance(ht, side: left) arm
      t2 distance(hb, side: left) arm
      t3 distance(hb, side: right) arm
    }
  }
  construction rack_tooth := solid(face(t0, t1, t2, t3, -> close), from: at - 2mm,
                                   to: at + wring + 2mm)

  // edge on: the band, the tips its outline, and the root lines across it
  in o_s.plane {
    band := engine.parts.Box(o_s, x0: at, y0: -rfw, x1: at + wring, y1: rfw)
    ra := engine.parts.At(o_s, dx: at, dy: rring - hf)
    rb := engine.parts.At(o_s, dx: at + wring, dy: rring - hf)
    rc := engine.parts.At(o_s, dx: at, dy: hf - rring)
    rd := engine.parts.At(o_s, dx: at + wring, dy: hf - rring)
    root_t := line(ra.p, rb.p)
    root_b := line(rc.p, rd.p)
  }
  // The ring: its blank bored to the rim it is shrunk on, less every tooth space.  Blank and bore
  // are prisms of the end view's circles, whose seams lie in one half-plane, as the one sector the
  // build turns round needs; a blank turned from a section is built by its meridian, which the
  // build reads in the half-plane toward the world's x — no direction at all about the crank's
  // axis, which is the world's x.
  construction blank := solid(face(tip), from: at, to: at + wring)
  construction bored := solid(face(bore), from: at - 1mm, to: at + wring + 1mm)
  gear := solid(blank)
  bored cut gear
  // What the rack rolls through: the blank where its tooth goes, a block about the space it cuts
  // at roll 0 from inside the root to past the tip.  Seen from the ring, the tooth never leaves
  // its space, so it meets the block over the roll it meets the ring; and the block is no
  // operand of the ring, so the roll is read once, not again through every space the ring has.
  in o.plane {
    construction z0 := point hint(at: o, toward: arm.p2, by: hypot(rring - 10mm, 12mm) / R,
                                  turn: -atan(12mm / (rring - 10mm)))
    construction z1 := point hint(at: o, toward: arm.p2, by: hypot(rfw + 1mm, 12mm) / R,
                                  turn: -atan(12mm / (rfw + 1mm)))
    construction z2 := point hint(at: o, toward: arm.p2, by: hypot(rfw + 1mm, 12mm) / R,
                                  turn: atan(12mm / (rfw + 1mm)))
    construction z3 := point hint(at: o, toward: arm.p2, by: hypot(rring - 10mm, 12mm) / R,
                                  turn: atan(12mm / (rring - 10mm)))
    o distance(rring - 10mm, along: arm) z0
    o distance(rfw + 1mm, along: arm) z1
    o distance(rfw + 1mm, along: arm) z2
    o distance(rring - 10mm, along: arm) z3
    z0 distance(12mm, side: right) arm
    z1 distance(12mm, side: right) arm
    z2 distance(12mm, side: left) arm
    z3 distance(12mm, side: left) arm
  }
  construction zone := solid(face(z0, z1, z2, z3, -> close), from: at, to: at + wring)

  // The ring turns about the axis and the rack slides along its pitch line a pitch circle's turn
  // a turn: the rack rolls on the pitch circle.  Each joint's axis runs the way what it is held
  // to does — the turn's out of the end view, along the shaft as the band runs; the slide's the
  // way its pitch line runs — so the roll is the one the rack cuts by, whatever a start was.
  turn := frame
  turn spins(1) o
  rack slides(2 * pi * rring) slide
  construction space := sweep(rack_tooth, through: zone, seen_from: turn)
  repeat zr as i {
    construction indexed := space at(under: turn) i * 360deg / zr
    indexed cut gear
  }
}

// The crankshaft on its axis: `o` and `ax` where the end section shows it, `o_s` where the side
// section does, and `theta` the crank's turn — a formal, so the assembly says where it stands, or
// leaves it to the solve.  Each pin is read by the rod that rides it, in both views at once
// (`pin1` to `pin4`, cylinder by cylinder).
part Crankshaft(o: point, ax: line, o_s: point, theta: Angle) {
  // the shaft's own dimensions
  eP := rp + 12mm        // the pin's eye, outside
  rcw := 55mm            // the counterweight rim, clear of the cylinder walls' foot at the top
  hcw := 50mm            // half the web's width at the rim: the counterweight flares past the eye
  wj := 24mm             // a main journal's length along the axis
  wpin := pinlen         // a crank pin's length: the table's, since the rod's big end rides it
  web := P / 2 - (wj + wpin) / 2   // a web's thickness along the axis: what the pitch leaves
  rnose := 16mm          // the nose the pulley sits on
  oilr := 2.5mm          // the oil passage, half its bore
  throw_dims := {eye: eP, rim: rcw, half_width: hcw, oil_radius: oilr}
  // the nose: a keyway for the pulley's key, and the tapped bore the pulley's bolt screws into
  wkey := 5mm
  dkey := 3mm
  rtap := 5mm
  dtap := 30mm
  // the flywheel: its face toward the engine on the flange, the ring gear's seat and the
  // shoulder behind it, a dish turned in its engine side, and at the back the clutch face, with
  // the cover's seat stepped back outside it and a recess for the bolt heads inside it
  xfw := back + 8mm + wflange
  rsh := rfw - 8mm
  rdo := rseat - 12mm    // the dish, outside…
  rdi := rflange + 8mm   // …and inside
  dish := 8mm
  rfo := rfw - 20mm      // the clutch face, outside…
  rfi := 75mm            // …and inside
  step := 3mm
  recess := 4mm
  rhub := 32mm           // the flywheel's bore, over the flange's pilot
  rbc := 45mm            // the bolt circle through flywheel and flange
  rbolt := 5mm
  rpilot := 11mm         // the gearbox shaft's pilot bearing, bored in the flange
  dpilot := 16mm

  // -- along the axis: the section through cylinder 1 -------------------------------------
  in o.plane {
    main := circle(center: o) hint(r: rj)
    radius(rj) main
    path := circle(center: o) hint(r: R)
    radius(R) path
    t1 := Throw(o, ax, theta: theta, shape: throw_dims)
    t2 := Throw(o, ax, theta: theta + 180deg, shape: throw_dims)
    // what the shaft is turned to at either end, seen end on: the nose, the seal journal, the
    // flange and the flywheel, which the solid sweeps along the axis
    construction nose_c := circle(center: o) hint(r: rnose)
    construction seal_c := circle(center: o) hint(r: rseal)
    construction flange_c := circle(center: o) hint(r: rflange)
    construction flywheel_c := circle(center: o) hint(r: rfw)
    radius(rnose) nose_c
    radius(rseal) seal_c
    radius(rflange) flange_c
    radius(rfw) flywheel_c
    construction seat_c := circle(center: o) hint(r: rseat)
    construction shoulder_c := circle(center: o) hint(r: rsh)
    construction dish_o := circle(center: o) hint(r: rdo)
    construction dish_i := circle(center: o) hint(r: rdi)
    construction face_o := circle(center: o) hint(r: rfo)
    construction face_i := circle(center: o) hint(r: rfi)
    construction hub_c := circle(center: o) hint(r: rhub)
    construction pilot_c := circle(center: o) hint(r: rpilot)
    construction tap_c := circle(center: o) hint(r: rtap)
    radius(rseat) seat_c
    radius(rsh) shoulder_c
    radius(rdo) dish_o
    radius(rdi) dish_i
    radius(rfo) face_o
    radius(rfi) face_i
    radius(rhub) hub_c
    radius(rpilot) pilot_c
    radius(rtap) tap_c
    // the keyway in the nose, on throw 1's arm
    construction k0 := point hint((o.x + (rnose - dkey) * sin(theta) + wkey / 2 * cos(theta),
                                   o.y + (rnose - dkey) * cos(theta) - wkey / 2 * sin(theta)))
    construction k1 := point hint((o.x + (rnose + 2mm) * sin(theta) + wkey / 2 * cos(theta),
                                   o.y + (rnose + 2mm) * cos(theta) - wkey / 2 * sin(theta)))
    construction k2 := point hint((o.x + (rnose + 2mm) * sin(theta) - wkey / 2 * cos(theta),
                                   o.y + (rnose + 2mm) * cos(theta) + wkey / 2 * sin(theta)))
    construction k3 := point hint((o.x + (rnose - dkey) * sin(theta) - wkey / 2 * cos(theta),
                                   o.y + (rnose - dkey) * cos(theta) + wkey / 2 * sin(theta)))
    o distance(rnose - dkey, along: t1.arm) k0
    o distance(rnose + 2mm, along: t1.arm) k1
    o distance(rnose + 2mm, along: t1.arm) k2
    o distance(rnose - dkey, along: t1.arm) k3
    k0 distance(wkey / 2, side: right) t1.arm
    k1 distance(wkey / 2, side: right) t1.arm
    k2 distance(wkey / 2, side: left) t1.arm
    k3 distance(wkey / 2, side: left) t1.arm
  }
  // the bolts through flywheel and flange, six on their circle between the throws
  repeat 6 as k {
    in o.plane {
      construction bc := point hint((o.x + rbc * sin(theta + 30deg + k * 60deg),
                                     o.y + rbc * cos(theta + 30deg + k * 60deg)))
      o distance(rbc) bc
      construction spoke := line(o, bc)
      t1.arm angle(30deg + k * 60deg, sense: cw) spoke
      construction bolt := circle(center: bc) hint(r: rbolt)
      radius(rbolt) bolt
    }
  }
  // the oil drillings, in the plane through the axis and the throws: each main journal but the
  // last fed to the pin behind it, slantwise through the web from the journal's far side to the
  // pin's, a little past both surfaces.  In the plane, `x` runs along the axis and `y` along
  // throw 1's arm
  throws := plane(u: hint(dir: o.plane.normal), v: hint(dir: t1.arm))
  throws.origin coincident o
  throws.u parallel o.plane.normal
  throws.v parallel t1.arm
  repeat 4 as i {
    in throws {
      xj := front + 25mm + i * P
      sg := 1 - i * (3 - i)          // which way the pin stands: 1 on throw 1, -1 on throw 2
      construction oil_a := point hint((xj - 1.5mm, -sg * (rj + 3mm)))
      construction oil_b := point hint((xj + P / 2 + 1.5mm, sg * (R + rp + 3mm)))
      oil_a offset(dx: xj - 1.5mm, dy: -sg * (rj + 3mm)) throws.origin
      oil_b offset(dx: xj + P / 2 + 1.5mm, dy: sg * (R + rp + 3mm)) throws.origin
      construction drilling := line(oil_a, oil_b)
      // half the drilling's section, turned about its centre line
      construction oil_c := point hint((xj - 1.5mm - sg * oilr, -sg * (rj + 3mm)))
      construction oil_d := point hint((xj + P / 2 + 1.5mm - sg * oilr, sg * (R + rp + 3mm)))
      oil_c distance(oilr, side: left) drilling
      oil_d distance(oilr, side: left) drilling
      oil_a level(drilling) oil_c
      oil_b level(drilling) oil_d
    }
  }
  // the starter's ring gear on the flywheel's rim
  ring := StarterRing(o, t1.arm, o_s, at: xfw)

  // -- across the axis: the whole shaft edge on ------------------------------------------
  repeat 5 as j {
    in o_s.plane {
      jc := engine.parts.At(o_s, dx: front + 25mm + j * P, dy: 0mm)
      journal := engine.parts.Box(jc.p, x0: -wj / 2, y0: -rj, x1: wj / 2, y1: rj)
    }
  }
  repeat 4 as i {
    in o_s.plane {
      xc := front + 25mm + P / 2 + i * P
      // cylinders 1 and 4 are up together, 2 and 3 a half turn on
      k := i * (3 - i) / 2
      ph := theta + 180deg * k
      pin_s := point hint((o_s.x + xc, o_s.y + R * cos(ph)))
      o_s distance(xc, along: u) pin_s
      pin := engine.parts.Box(pin_s, x0: -wpin / 2, y0: -rp, x1: wpin / 2, y1: rp)
      // the throw's crown and heel at this cylinder, their heights the end view's
      ct := point hint((o_s.x + xc, o_s.y + (R + eP) * cos(ph)))
      hb := point hint((o_s.x + xc, o_s.y - rcw * cos(ph)))
      o_s distance(xc, along: u) ct
      o_s distance(xc, along: u) hb
      wl := WebSide(o_s, x0: xc - P / 2 + wj / 2, x1: xc - wpin / 2, top: ct, bottom: hb)
      wr := WebSide(o_s, x0: xc + wpin / 2, x1: xc + P / 2 - wj / 2, top: ct, bottom: hb)
    }
  }
  in o_s.plane {
    // the nose the pulley sits on, forward of the first journal; behind the last, the seal
    // journal through the block's rear wall, then the flange, and the flywheel on it behind the
    // ring gear: its shoulder, and the clutch face standing out of the cover's seat
    nose := engine.parts.Box(o_s, x0: front - 70mm, y0: -rnose, x1: front + 25mm - wj / 2, y1: rnose)
    seal := engine.parts.Box(o_s, x0: back - 25mm + wj / 2, y0: -rseal, x1: back + 8mm, y1: rseal)
    flange := engine.parts.Box(o_s, x0: back + 8mm, y0: -rflange, x1: xfw, y1: rflange)
    shoulder := engine.parts.Box(o_s, x0: xfw + wring, y0: -rsh, x1: xfw + wfw - step, y1: rsh)
    clutch := engine.parts.Box(o_s, x0: xfw + wfw - step, y0: -rfo, x1: xfw + wfw, y1: rfo)
    claim journal[0].a distance(wj, along: u) journal[0].b
    claim pin[0].a distance(wpin, along: u) pin[0].b
  }

  // -- the two views agree: each pin, crown and heel is where the section puts it --------
  t1.pin project pin_s[0]
  t2.pin project pin_s[1]
  t2.pin project pin_s[2]
  t1.pin project pin_s[3]
  t1.crown project ct[0]
  t2.crown project ct[1]
  t2.crown project ct[2]
  t1.crown project ct[3]
  t1.heel project hb[0]
  t2.heel project hb[1]
  t2.heel project hb[2]
  t1.heel project hb[3]

  // -- what rides on it: each cylinder's pin in both views, cylinders 1 and 4 on `t1`, 2 and 3
  // on `t2` (an inline four's pins lie in one plane)
  pin1 := {end: t1.pin, side: pin_s[0]}
  pin2 := {end: t2.pin, side: pin_s[1]}
  pin3 := {end: t2.pin, side: pin_s[2]}
  pin4 := {end: t1.pin, side: pin_s[3]}

  // -- the shaft as a solid: each piece the end section draws, swept along the axis over the
  // stretch the side section gives it (the end view's normal runs along the axis, from the front)
  shaft := solid()
  repeat 5 as j {
    private journal_b := solid(face(main), from: front + 25mm + j * P - wj / 2,
                               to: front + 25mm + j * P + wj / 2)
    journal_b union shaft
  }
  repeat 4 as i {
    xw := front + 25mm + P / 2 + i * P
    // cylinders 1 and 4 on the first throw, 2 and 3 on the second
    when i * (3 - i) == 0 {
      private pin_b := solid(face(t1.kp), from: xw - wpin / 2, to: xw + wpin / 2)
      private web_l := solid(face(t1.eye, t1.fl, t1.rim, t1.fr), from: xw - P / 2 + wj / 2,
                             to: xw - wpin / 2)
      private web_r := solid(face(t1.eye, t1.fl, t1.rim, t1.fr), from: xw + wpin / 2,
                             to: xw + P / 2 - wj / 2)
    }
    when i * (3 - i) != 0 {
      private pin_b := solid(face(t2.kp), from: xw - wpin / 2, to: xw + wpin / 2)
      private web_l := solid(face(t2.eye, t2.fl, t2.rim, t2.fr), from: xw - P / 2 + wj / 2,
                             to: xw - wpin / 2)
      private web_r := solid(face(t2.eye, t2.fl, t2.rim, t2.fr), from: xw + wpin / 2,
                             to: xw + P / 2 - wj / 2)
    }
    pin_b union shaft
    web_l union shaft
    web_r union shaft
  }
  nose_b := solid(face(nose_c), from: front - 70mm, to: front + 25mm - wj / 2)
  seal_b := solid(face(seal_c), from: back - 25mm + wj / 2, to: back + 8mm)
  flange_b := solid(face(flange_c), from: back + 8mm, to: xfw)
  nose_b union shaft
  seal_b union shaft
  flange_b union shaft
  // the flywheel: the seat the ring is shrunk on, the shoulder behind it, and what is turned in
  seat_b := solid(face(seat_c), from: xfw, to: xfw + wring)
  rim_b := solid(face(shoulder_c), from: xfw + wring, to: xfw + wfw)
  seat_b union shaft
  rim_b union shaft
  dished := solid(face(dish_o, holes: dish_i), from: xfw - 1mm, to: xfw + dish)
  cover_seat := solid(face(flywheel_c, holes: face_o), from: xfw + wfw - step, to: xfw + wfw + 1mm)
  heads := solid(face(face_i), from: xfw + wfw - recess, to: xfw + wfw + 1mm)
  hub := solid(face(hub_c), from: xfw, to: xfw + wfw + 1mm)
  dished cut shaft
  cover_seat cut shaft
  heads cut shaft
  hub cut shaft
  repeat 6 as k {
    private drill := solid(face(bolt[k]), from: back + 6mm, to: xfw + wfw + 1mm)
    drill cut shaft
  }
  repeat 4 as i {
    private oilway := solid(face(oil_a[i], oil_b[i], oil_d[i], oil_c[i], -> close),
                            about: drilling[i])
    oilway cut shaft
  }
  // the pilot bearing's bore in the flange, run out through the flywheel's bore as the gearbox
  // shaft enters it (a cutter stopping a millimetre into that bore's air left the mesh sagging
  // past the export's tolerance), and the nose's keyway and tapped bore
  pilot := solid(face(pilot_c), from: xfw - dpilot, to: xfw + wfw + 1mm)
  keyway := solid(face(k0, k1, k2, k3, -> close), from: front - 72mm, to: front - 28mm)
  tapped := solid(face(tap_c), from: front - 72mm, to: front - 70mm + dtap)
  pilot cut shaft
  keyway cut shaft
  tapped cut shaft
}

